"""Generate src/unicode_data.c: sorted codepoint ranges with category flags used
by the hand-written BPE pre-tokenizers (\\p{L} subclasses, \\p{M}, \\p{N}, \\s).

    python3 scripts/gen_unicode.py > src/unicode_data.c
"""
import sys
import unicodedata

F_LU, F_LL, F_LT, F_LM, F_LO, F_M, F_N, F_SPACE = 1, 2, 4, 8, 16, 32, 64, 128
CAT = {"Lu": F_LU, "Ll": F_LL, "Lt": F_LT, "Lm": F_LM, "Lo": F_LO,
       "Mn": F_M, "Mc": F_M, "Me": F_M, "Nd": F_N, "Nl": F_N, "No": F_N}
# Unicode White_Space property (what regex \s matches in the HF tokenizers / Oniguruma)
WHITE = set(range(0x9, 0xE)) | {0x20, 0x85, 0xA0, 0x1680, 0x2028, 0x2029, 0x202F, 0x205F, 0x3000} | set(range(0x2000, 0x200B))

ranges = []
cur = None
for cp in range(0x110000):
    f = CAT.get(unicodedata.category(chr(cp)), 0) | (F_SPACE if cp in WHITE else 0)
    if cur and cur[2] == f and cur[1] == cp - 1:
        cur[1] = cp
    else:
        if cur and cur[2]:
            ranges.append(tuple(cur))
        cur = [cp, cp, f]
if cur and cur[2]:
    ranges.append(tuple(cur))

out = sys.stdout
out.write(f"// Generated by scripts/gen_unicode.py from Python {sys.version.split()[0]} unicodedata "
          f"(Unicode {unicodedata.unidata_version}). Do not edit.\n")
out.write('#include "unicode.h"\n\n')
out.write(f"const unicode_range unicode_ranges[{len(ranges)}] = {{\n")
for lo, hi, f in ranges:
    out.write(f"    {{0x{lo:X}, 0x{hi:X}, {f}}},\n")
out.write("};\n")
out.write(f"const int unicode_n_ranges = {len(ranges)};\n")
